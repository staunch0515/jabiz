// Generates the site's types from the catalog of the public templates (docs/culture/00-design.md section 7.2;
// docs/design/15-public-access.md section 7), as the admin generates its types from the OpenAPI document.
//   node scripts/gen-public-api.mjs           writes src/api/public-queries.ts
//   node scripts/gen-public-api.mjs --check   fails when that file differs from what the catalog gives
// The catalog is written by the backend's PublicQueriesSnapshotIT (-Dpublic-queries.update-snapshot=true).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = join(root, 'src/api/public-queries.json')
const OUTPUT = join(root, 'src/api/public-queries.ts')

/** The TypeScript type of a value of a semantic kind (docs/design/02-metamodel.md section 8), as JSON carries it. */
export function tsType(kind) {
  switch (kind.type) {
    case 'text':
    case 'semanticIdentity':
    case 'reference':
      return 'string'
    case 'temporal':
      // ISO-8601 instants.
      return 'string'
    case 'code':
      // Database dictionaries (no allowed values) grow without a release: any string.
      return kind.allowedValues?.length ? kind.allowedValues.map((v) => JSON.stringify(v)).join(' | ') : 'string'
    case 'numeric':
    case 'version':
      return 'number'
    case 'bool':
      return 'boolean'
    case 'custom':
      if (kind.kindId === 'jabiz.i18n-text') return 'LocalizedText'
      if (kind.kindId === 'jabiz.file') return 'FileId'
      break
  }
  throw new Error(`No TypeScript type for kind ${JSON.stringify(kind)}`)
}

const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name))
const union = (names) => (names.length ? names.map((n) => JSON.stringify(n)).join(' | ') : 'never')

function params(spec) {
  const entries = Object.entries(spec)
  if (!entries.length) return 'Record<string, never>'
  const fields = entries.map(([name, p]) => {
    const type = tsType(p.kind)
    return `      ${key(name)}${p.required ? '' : '?'}: ${p.list ? `readonly (${type})[]` : type}`
  })
  return `{\n${fields.join('\n')}\n    }`
}

function row(results) {
  // A result column may be empty (a nullable field, an outer join): every value may be null.
  const fields = Object.entries(results).map(([name, kind]) => `      ${key(name)}: ${tsType(kind)} | null`)
  return `{\n${fields.join('\n')}\n    }`
}

/** The generated module for a catalog. */
export function render(catalog) {
  const queries = [...catalog.queries].sort((a, b) => a.id.localeCompare(b.id))
  const entries = queries.map((q) => {
    const doc = q.description ? `  /** ${q.description.replaceAll('*/', '*\\/')} */\n` : ''
    return `${doc}  ${JSON.stringify(q.id)}: {
    params: ${params(q.params)}
    row: ${row(q.results)}
    filters: ${union(q.list.filters)}
    sorts: ${union(q.list.sorts)}
  }`
  })
  const cache = queries.map((q) => `  ${JSON.stringify(q.id)}: ${q.cacheSeconds},`)
  return `// Generated by scripts/gen-public-api.mjs from public-queries.json. Do not edit: run pnpm gen:api.

export type Locale = 'zh' | 'ja' | 'en'

/** A multilingual text: its value in each language that has one (the others fall back, 16 section 1). */
export type LocalizedText = Partial<Record<Locale, string>>

/** A file's id: GET /api/public/files/{id}[/{variant}]. */
export type FileId = string

/** The public templates: parameters (p.<name>), rows, outer filters and sorts. */
export interface PublicQueries {
${entries.join('\n')}
}

export type PublicQueryId = keyof PublicQueries
export type QueryParams<Q extends PublicQueryId> = PublicQueries[Q]['params']
export type QueryRow<Q extends PublicQueryId> = PublicQueries[Q]['row']
export type QueryFilter<Q extends PublicQueryId> = PublicQueries[Q]['filters']
export type QuerySort<Q extends PublicQueryId> = PublicQueries[Q]['sorts']

/** A page of a public template: GET /api/public/queries/{id}. */
export interface QueryPage<Q extends PublicQueryId> {
  items: QueryRow<Q>[]
  total: number | null
  offset: number
  limit: number
}

/** How long responses may be cached (seconds), per template. */
export const cacheSeconds: Record<PublicQueryId, number> = {
${cache.join('\n')}
}
`
}

function main(args) {
  const generated = render(JSON.parse(readFileSync(CATALOG, 'utf8')))
  if (args.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUTPUT, 'utf8')
    } catch {
      // Missing: differs.
    }
    if (current !== generated) {
      console.error('src/api/public-queries.ts is not what public-queries.json gives: run pnpm gen:api and commit it')
      process.exit(1)
    }
    return
  }
  writeFileSync(OUTPUT, generated)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2))
}
