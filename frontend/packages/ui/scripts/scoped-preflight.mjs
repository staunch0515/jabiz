// Tailwind's preflight, scoped to the elements of the new components (phase 15a, decision D34 item 6):
//   node packages/ui/scripts/scoped-preflight.mjs        rewrites src/styles/preflight.scoped.css
// While Ant Design pages remain, a global reset would restyle them; the scoped copy resets only elements that are
// `.jabiz-ui` or inside one. Every element the components draw carries the class, so the reset reaches a component
// wherever a page puts it, and never the page around it. Selectors keep their specificity (the scope is inside
// :where), so utilities override them as they would the global preflight. theme.test.ts fails when the copy no
// longer matches the installed Tailwind.
// Phase 15d removes this script and imports 'tailwindcss/preflight.css'.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'

export const SCOPE = 'jabiz-ui'

/** Splits at commas outside parentheses and strings. */
function splitTopLevel(text, separator) {
  const parts = []
  let depth = 0
  let quote = null
  let start = 0
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quote) {
      if (c === quote) quote = null
    } else if (c === '"' || c === "'") quote = c
    else if (c === '(') depth++
    else if (c === ')') depth--
    else if (c === separator && depth === 0) {
      parts.push(text.slice(start, i))
      start = i + 1
    }
  }
  parts.push(text.slice(start))
  return parts.map((p) => p.trim()).filter((p) => p !== '')
}

/** Index of the first `::` outside parentheses (the pseudo-element, which must stay last), or -1. */
function pseudoElementAt(selector) {
  let depth = 0
  for (let i = 0; i < selector.length - 1; i++) {
    const c = selector[i]
    if (c === '(') depth++
    else if (c === ')') depth--
    else if (depth === 0 && c === ':' && selector[i + 1] === ':') return i
  }
  return -1
}

export function scopeSelector(selector, scope = SCOPE) {
  // The document's own rules apply to the scope's root instead.
  if (['html', ':host', 'body'].includes(selector)) return `:where(.${scope})`
  const at = pseudoElementAt(selector)
  const base = at < 0 ? selector : selector.slice(0, at)
  const pseudo = at < 0 ? '' : selector.slice(at)
  // The subject itself is a scoped element or inside one: the condition goes onto the last compound.
  const within = `:where(.${scope}, .${scope} *)`
  const scoped = base === '' || base === '*' ? within : `${base}${within}`
  return scoped + pseudo
}

/** Index just after the brace that closes the block opening at `open`. */
function blockEnd(css, open) {
  let depth = 0
  for (let i = open; i < css.length; i++) {
    if (css.startsWith('/*', i)) {
      i = css.indexOf('*/', i + 2) + 1
      continue
    }
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) return i + 1
  }
  throw new Error('preflight: unbalanced braces')
}

/** The style sheet with every rule's selectors scoped; at-rules (@supports) are kept and their rules scoped. */
export function scopePreflight(css, scope = SCOPE) {
  let out = ''
  let i = 0
  while (i < css.length) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2) + 2
      out += css.slice(i, end)
      i = end
      continue
    }
    if (/\s/.test(css[i])) {
      out += css[i++]
      continue
    }
    const open = css.indexOf('{', i)
    if (open < 0) {
      out += css.slice(i)
      break
    }
    const end = blockEnd(css, open)
    const prelude = css.slice(i, open)
    const body = css.slice(open + 1, end - 1)
    if (prelude.trimStart().startsWith('@')) {
      out += `${prelude}{${scopePreflight(body, scope)}}`
    } else {
      const selectors = [...new Set(splitTopLevel(prelude.replace(/\/\*[\s\S]*?\*\//g, ''), ',').map((s) => scopeSelector(s, scope)))]
      out += `${selectors.join(',\n')} {${body}}`
    }
    i = end
  }
  return out
}

const HEADER = `/*
 * GENERATED by packages/ui/scripts/scoped-preflight.mjs from tailwindcss/preflight.css: do not edit.
 * Tailwind's preflight, scoped to .jabiz-ui while Ant Design pages remain (phase 15, decision D34).
 */
`

/** The scoped preflight of the installed Tailwind, as the committed file holds it. */
export function generate() {
  const require = createRequire(import.meta.url)
  const source = readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf8')
  return HEADER + scopePreflight(source)
}

export const OUTPUT = resolve(import.meta.dirname, '../src/styles/preflight.scoped.css')

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  writeFileSync(OUTPUT, generate())
  console.log(`wrote ${OUTPUT}`)
}
