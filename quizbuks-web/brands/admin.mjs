// The brand profiles for the admin and operator back offices (Q55b): `node quizbuks-web/brands/admin.mjs` writes
// backend/quizbuks/admin-extension/src/brands.generated.ts. The extension is compiled by the platform's frontend, which
// serves nothing outside the extension's directory, so it cannot read the profiles here; the generated module holds
// every profile's name, mark and icon, and the build picks one by QB_BRAND (VITE_QB_BRAND). admin.test.mjs checks the
// committed module is up to date.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { brandIds, loadBrand } from './brand.mjs'

const here = dirname(fileURLToPath(import.meta.url))
export const ADMIN_MODULE = resolve(here, '../../backend/quizbuks/admin-extension/src/brands.generated.ts')

/**
 * The mark as an image of its own: mark.svg paints with the brand tokens (var(--qb-…)), which an image cannot read
 * from a page, so they are written in with the light appearance's values from the profile's brand.css.
 */
export function standaloneMark(svg, css) {
  const root = /:root\s*\{([^}]*)\}/.exec(css)?.[1] ?? ''
  const tokens = new Map([...root.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]))
  const resolved = svg.trim().replace(/var\((--[\w-]+)\)/g, (_, name) => {
    if (!tokens.has(name)) throw new Error(`the mark uses ${name}, which brand.css does not give`)
    return tokens.get(name)
  })
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(resolved)}`
}

/** The module's source. */
export function adminBrandsModule() {
  const entries = brandIds().map((id) => {
    const brand = loadBrand(id)
    const read = (file, encoding) => readFileSync(join(brand.dir, file), encoding)
    return `  ${JSON.stringify(id)}: {
    name: ${JSON.stringify(brand.name)},
    logo: ${JSON.stringify(standaloneMark(read('mark.svg', 'utf8'), read('brand.css', 'utf8')))},
    favicon: ${JSON.stringify(`data:image/png;base64,${read('public/icon-192.png').toString('base64')}`)},
  },`
  })
  return `// Generated by quizbuks-web/brands/admin.mjs from the brand profiles (Q55b); do not edit.

/** Every brand profile's name, mark and tab icon (images as data URIs). */
export const BRAND_PROFILES: Record<string, { name: string; logo: string; favicon: string }> = {
${entries.join('\n')}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(ADMIN_MODULE, adminBrandsModule())
  console.log(`admin brands → ${ADMIN_MODULE}`)
}
